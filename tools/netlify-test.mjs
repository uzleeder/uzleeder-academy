import assert from 'node:assert/strict';
import crypto from 'node:crypto';
process.env.SESSION_SECRET='academy-adapter-test-only';
Object.assign(process.env,{AUTH_USER:'test',AUTH_PASSWORD_HASH:'test-only',KV_REST_API_URL:'https://db.invalid',KV_REST_API_TOKEN:'test-only'});
globalThis.Netlify={env:{get:k=>process.env[k]}};
const {default:gate}=await import('../netlify/edge-functions/auth.js');
const {default:api}=await import('../netlify/functions/gateway.mjs');
let passed=0;const context={ip:'192.0.2.10',next:async()=>{passed++;return new Response('next')}};
assert.equal((await gate(new Request('https://academy.test/',{headers:{accept:'text/html'}}),context)).status,302);
assert.equal((await gate(new Request('https://academy.test/api/state'),context)).status,401);
assert.equal((await gate(new Request('https://academy.test/.netlify/functions/gateway'),context)).status,404);
assert.equal((await gate(new Request('https://academy.test/login'),context)).status,200);
const body=Buffer.from(JSON.stringify({u:'test',exp:Date.now()+60000})).toString('base64url');
const token=body+'.'+crypto.createHmac('sha256',process.env.SESSION_SECRET).update(body).digest('base64url');
assert.equal((await gate(new Request('https://academy.test/',{headers:{cookie:'uzla_session='+token}}),context)).status,200);
assert.equal(passed,2);
assert.equal((await api(new Request('https://academy.test/api/ctrl/io'),context)).status,401);
const logout=await api(new Request('https://academy.test/api/logout',{method:'POST',body:'{}'}),context);
assert.equal(logout.status,200);assert.equal(logout.headers.getSetCookie().length,2);
assert.equal((await api(new Request('https://academy.test/api/unknown'),context)).status,404);
console.log('PASS Netlify adapter: protected pages/API, direct URL blocked, valid session, controller auth, both logout cookies, unknown route.');
