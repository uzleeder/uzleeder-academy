  /* --- Yordamchi funksiyalar ---------------------------------------------
     tr(key, vars) — interfeys matni. Kalit topilmasa uz'ga, u ham bo'lmasa
     kalitning o'ziga qaytadi (ekranda "undefined" chiqmasin).            */
  window.tr = function (key, vars) {
    var lang = window.Store ? Store.get('lang') : 'uz';
    var table = STRINGS[lang] || STRINGS.uz;
    var s = table[key];
    if (s === undefined) s = STRINGS.uz[key];
    if (s === undefined) return key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split('{' + k + '}').join(String(vars[k]));
      });
      /* Inglizcha birlik: "1 days" → "1 day" (o'zbekchada ko'plik qo'shimchasi yo'q) */
      if (lang === 'en') s = s.replace(/\b1 (days|lessons|notes|weeks|hours|minutes|words|units|passages|certificates|projects|mistakes|sections|questions)\b/g, function (m, w) { return '1 ' + w.slice(0, -1); });
    }
    return s;
  };

  /* L(obj) — kontent obyekti {uz:"…", en:"…"} dan joriy tilni tanlaydi.
     Tarjima yo'q bo'lsa — bor tilini qaytaradi (bo'sh joy qolmasin).   */
  window.L = function (obj) {
    if (obj === null || obj === undefined) return '';
    if (typeof obj === 'string') return obj;
    var lang = window.Store ? Store.get('lang') : 'uz';
    if (Array.isArray(obj)) return obj;
    return obj[lang] || obj.uz || obj.en || '';
  };
